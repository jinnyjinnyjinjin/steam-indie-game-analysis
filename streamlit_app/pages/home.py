# 현재 앱의 역할
# ============================================================
st.header("현재 Streamlit 앱의 역할")

st.markdown(
    """
    이 앱은 **분석 결과를 개발자가 읽고 바로 활용할 수 있는 형태로 바꾸는 의사결정 보조 도구**입니다.

    | 구분 | 역할 |
    | --- | --- |
    | 출시 전 | 유사한 인디게임의 초기 리뷰 반응을 바탕으로 출시 전 점검 항목을 정리합니다. |
    | 출시 후 | 선택한 게임의 리뷰 이슈를 바탕으로 패치와 운영에서 먼저 확인할 문제를 정리합니다. |
    | 근거 확인 | 결과에 사용된 이슈 요약, 근거 데이터, 리뷰 샘플을 함께 보여줍니다. |
    | 결과 활용 | 회의 자료, QA 체크리스트, 패치 우선순위 논의, 운영 방향 정리에 활용할 수 있습니다. |
    """
)

role_col1, role_col2 = st.columns(2)

with role_col1:
    with st.container(border=True):
        st.subheader("✅ 이 앱이 해주는 것")
        st.markdown(
            """
            - 리뷰 분석 결과를 개발자가 읽기 쉬운 형태로 요약합니다
            - 조건별 반복 이슈를 바탕으로 출시 전 체크리스트를 생성합니다
            - 게임별 반복 이슈를 바탕으로 패치·운영 방향을 제안합니다
            - 결과를 뒷받침하는 근거 데이터와 리뷰 샘플을 제공합니다
            """
        )

with role_col2:
    with st.container(border=True):
        st.subheader("⚠️ 이 앱이 하지 않는 것")
        st.markdown(
            """
            - 게임의 성공 여부를 확정적으로 예측하지 않습니다
            - 새로운 Steam 리뷰를 실시간으로 수집하지 않습니다
            - 리뷰 원문 전체를 매번 다시 분류하지 않습니다
            - 개발자의 최종 판단을 대신하지 않습니다
            """
        )

