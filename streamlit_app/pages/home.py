import streamlit as st


# ============================================================
# 홈 화면
# ============================================================
st.title("🎮 Steam 인디게임 출시 전략 도우미")
st.markdown(
    """
    이 앱은 Steam 인디게임 리뷰 분석 결과를 개발자가 바로 확인할 수 있는 형태로 정리하는 **의사결정 보조 도구**입니다.

    출시 전에는 유사 게임의 초기 리뷰에서 반복된 강점과 리스크를 바탕으로  
    **무엇을 미리 점검해야 하는지** 확인할 수 있습니다.

    출시 후에는 실제 유저 리뷰에서 반복되는 문제와 긍정 요소를 바탕으로  
    **어떤 이슈를 먼저 확인하고 개선해야 하는지** 정리할 수 있습니다.
    """
    )

st.info(
    "이 앱은 Steam 리뷰를 실시간으로 새로 수집하지 않습니다.  \n"
    "새 리뷰를 반영하려면 별도의 데이터 수집과 분석 과정을 먼저 실행해야 합니다."
    )
st.divider()


# ============================================================
# 앱 핵심 기능
# ============================================================
st.header("이 앱에서 할 수 있는 일")

pre_col, post_col = st.columns(2)

with pre_col:
    with st.container(border=True):
        st.subheader("🧭 출시 전 체크리스트")
        st.markdown(
            """
            출시를 준비 중인 게임의 **장르, 가격대, Steam 태그, 플레이 방식**을 입력하면  
            비슷한 조건의 인디게임들이 출시 초기에 어떤 점을 칭찬받았고, 어떤 부분에서 불만이 반복되었는지 확인합니다.

            이를 바탕으로 개발자가 출시 전에 확인할 수 있는 **체크리스트**를 생성합니다.

            **이럴 때 사용합니다**
            - 출시 전에 UX, 난이도, 콘텐츠, 가격 관련 리스크를 점검하고 싶을 때
            - 비슷한 게임에서 자주 칭찬받거나 비판받은 요소를 확인하고 싶을 때
            - 팀 회의나 QA 과정에서 사용할 출시 전 체크리스트 초안이 필요할 때
            """
        )
        st.page_link(
            "pages/prelaunch_checklist.py",
            label="출시 전 체크리스트로 이동",
            icon="🧭",
        )

with post_col:
    with st.container(border=True):
        st.subheader("🛠️ 출시 후 패치·운영 제안")
        st.markdown(
            """
            이미 출시된 게임을 선택하면 Steam 리뷰에서 반복적으로 나타난 이슈를 정리하고,  
            패치와 운영 관점에서 어떤 항목을 먼저 확인해야 하는지 제안합니다.

            이를 바탕으로 개발자가 출시 후에 취해야할 **패치·운영**을 제안합니다.

            **이럴 때 사용합니다**
            - 부정 리뷰가 쌓였지만 원인을 빠르게 정리하기 어려울 때
            - 버그, 밸런스, 콘텐츠, 최적화 중 무엇을 먼저 볼지 정해야 할 때
            - 패치 노트나 운영 공지의 방향성을 잡기 위한 근거가 필요할 때
            """
        )
        st.page_link(
            "pages/postlaunch_report.py",
            label="출시 후 패치·운영 제안으로 이동",
            icon="🛠️",
        )

st.warning(
    "이 앱의 결과는 최종 정답이 아닌, 개발자가 빠르게 검토할 수 있도록 정리한 근거 기반 초안입니다.    \n"
    "최종 의사결정에는 개발 일정, 팀 리소스, 게임의 기획 의도, 커뮤니티 상황을 함께 고려해야 합니다."
)

st.divider()