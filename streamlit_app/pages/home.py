# ============================================================
# 홈 화면
# ============================================================
st.title("🎮 Steam 인디게임 출시 전략 도우미")
st.caption("출시 전 점검과 출시 후 패치·운영 판단을 돕는 개발자용 분석 앱")

st.markdown(
    """
    이 앱은 Steam 인디게임 리뷰 분석 결과를 바탕으로,  
    인디게임 개발자가 **출시 전에 무엇을 점검해야 하는지**,  
    출시 후에는 **어떤 문제를 먼저 확인하고 개선해야 하는지** 빠르게 정리할 수 있도록 만든 도구입니다.

    1. 출시 전에는 유사 게임의 초기 리뷰에서 반복된 점검 항목을 확인합니다.  
    2. 출시 후에는 선택한 게임의 반복 이슈와 대응 우선순위를 확인합니다.  
    3. 결과는 정답이 아니라 팀 회의와 QA, 패치 계획에 활용할 수 있는 근거 기반 초안입니다.
    """
)

st.divider()


# ============================================================
# 앱 핵심 기능
# ============================================================
st.header("이 앱에서 할 수 있는 일")

pre_col, post_col = st.columns(2)

with pre_col:
    with st.container(border=True):
        st.subheader("🧭 출시 전 체크리스트")
        st.write(
            "개발 중이거나 출시를 준비 중인 게임의 장르, 가격대, Steam 태그, 플레이 방식을 입력하면 "
            "유사한 인디게임의 초기 리뷰에서 반복된 강점과 리스크를 바탕으로 출시 전 점검 항목을 정리합니다."
        )
        st.markdown(
            """
            **이럴 때 사용합니다**
            - 출시 전에 점검해야 할 UX, 난이도, 콘텐츠, 가격 관련 리스크를 보고 싶을 때
            - 비슷한 게임에서 자주 칭찬받거나 비판받은 요소를 확인하고 싶을 때
            - 팀 회의용 출시 전 QA 체크리스트 초안이 필요할 때
            """
        )
        st.page_link(
            "pages/prelaunch_checklist.py",
            label="출시 전 체크리스트로 이동",
            icon="🧭",
        )

with post_col:
    with st.container(border=True):
        st.subheader("🛠️ 출시 후 패치·운영 전략")
        st.write(
            "이미 출시된 게임을 선택하면 리뷰에서 반복적으로 나타난 이슈를 정리하고, "
            "개발자가 어떤 문제를 먼저 확인해야 하는지 패치와 운영 관점에서 제안합니다."
        )
        st.markdown(
            """
            **이럴 때 사용합니다**
            - 부정 리뷰가 쌓였는데 원인을 빠르게 정리하고 싶을 때
            - 버그, 밸런스, 콘텐츠, 최적화 중 무엇을 먼저 볼지 정해야 할 때
            - 패치 노트나 운영 공지의 방향성을 잡기 위한 근거가 필요할 때
            """
        )
        st.page_link(
            "pages/postlaunch_report.py",
            label="출시 후 패치·운영으로 이동",
            icon="🛠️",
        )

st.divider()


# ============================================================
# 사용 방법
# ============================================================
st.header("사용 방법")

use_tab1, use_tab2 = st.tabs(["출시 전 사용 흐름", "출시 후 사용 흐름"])

with use_tab1:
    st.markdown(
        """
        ### 출시 전 체크리스트는 이렇게 사용합니다

        1. **게임 조건 입력**  
           개발하려는 게임에 가까운 장르, 가격대, Steam 태그, 플레이 방식을 선택합니다.

        2. **유사 조건의 반복 이슈 확인**  
           비슷한 조건의 인디게임 초기 리뷰에서 어떤 강점과 문제가 반복되었는지 확인합니다.

        3. **체크리스트 생성**  
           앱이 정리한 근거 데이터를 바탕으로 출시 전에 확인해야 할 점검 항목을 생성합니다.

        4. **개발팀 점검에 활용**  
           생성된 항목을 QA, 밸런스 조정, 튜토리얼 보완, 가격 검토, 스토어 페이지 점검 등에 활용합니다.
        """
    )

with use_tab2:
    st.markdown(
        """
        ### 출시 후 패치·운영 전략은 이렇게 사용합니다

        1. **분석 대상 게임 선택**  
           현재 앱에 분석 데이터가 준비된 게임 중 하나를 선택합니다.

        2. **현재 리뷰 상태 확인**  
           분석 리뷰 수, 부정·혼합 반응, 주요 이슈 태그, 시급도 분포를 먼저 확인합니다.

        3. **패치·운영 방향 생성**  
           반복적으로 언급된 문제와 근거 리뷰를 바탕으로 우선 확인할 이슈와 대응 방향을 정리합니다.

        4. **근거 데이터와 리뷰 샘플 검토**  
           최종 판단 전에 근거표와 실제 리뷰 샘플을 확인해 개발팀 상황에 맞게 우선순위를 조정합니다.
        """
    )

st.info(
    "처음 사용할 때는 출시 전 체크리스트 또는 출시 후 패치·운영 메뉴에서 기본 흐름대로 조건을 선택하시면 됩니다. "
    "결과를 확인한 뒤 필요하면 근거 데이터와 리뷰 샘플을 함께 검토해주세요."
)

st.divider()


